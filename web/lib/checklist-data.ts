/** Items that carry a real deadline, sorted ascending. */
export const datedItems = checklistItems
  .filter((item) => Boolean(item.due))
  .sort((a, b) => (a.due! < b.due! ? -1 : 1));

export function nextDeadline(now: Date = new Date()): ChecklistItem | null {
  const key = now.toISOString().slice(0, 10);
  return datedItems.find((item) => item.due! >= key) ?? null;
}

